import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CONFIG_FILE_NAME } from "./config.ts";

const TEMPLATE_DIR = fileURLToPath(new URL("../templates", import.meta.url));
export const GENERATED_MARKER = "generated by pi-cnb-cloud";

export function readTemplate(relativePath: string): string {
  return readFileSync(join(TEMPLATE_DIR, relativePath), "utf8");
}

export interface CnbYmlOptions {
  event: string;
  /** When set, run in this image directly instead of building .cnb/agent/Dockerfile. */
  image?: string;
  /** URL of a secret-repo file injected via `imports`. */
  imports?: string;
}

export function buildCnbYml(options: CnbYmlOptions): string {
  const { event, image } = options;
  const envBlock = [
    "      # 任务参数由本地插件通过 OpenAPI 注入（AGENT_TASK / AGENT_TITLE / AGENT_RUN_ID）。",
    "      # 模型与通知密钥不要写在这里，放 CNB 密钥仓库并用 imports 引入：",
    "      # imports: https://cnb.cool/<org>/<secret-repo>/-/blob/main/agent.yml",
    "      #   agent.yml: AGENT_API_KEY / AGENT_BASE_URL / AGENT_MODEL",
  ].join("\n");

  const dockerBlock = image
    ? [
        "      docker:",
        `        image: ${image}`,
        "        volumes:",
        "          - /root/.npm # 复用 npm 缓存，加速 pi 首次安装",
      ].join("\n")
    : [
        "      docker:",
        "        build:",
        "          dockerfile: .cnb/agent/Dockerfile",
        "          by:",
        "            - .cnb/agent/Dockerfile",
        "          versionBy:",
        "            - .cnb/agent/Dockerfile",
      ].join("\n");

  return `# ${GENERATED_MARKER} — 可以自由修改。
#
# 触发方式（本地 /cloud 命令就是调用它）：
#   POST {CNB_API_ENDPOINT}/{group}/{repo}/-/build/start
#   {"event":"${event}","branch":"main","env":{"AGENT_TASK":"...","AGENT_TITLE":"..."}}
#
# 注意：event 名必须以 api_trigger 开头，且与本地 .pi/cnb-cloud.json 的 event 一致。
$:
  ${event}:
    - name: pi-cloud-agent
${options.imports ? `      imports:\n        - ${options.imports}\n` : ""}${envBlock}
${dockerBlock}
      stages:
        - name: pi cloud agent
          script: bash .cnb/agent/run.sh
`;
}

export interface ScaffoldResult {
  written: string[];
  skipped: string[];
}

export interface ScaffoldOptions extends CnbYmlOptions {
  testCommand?: string;
  maxIterations?: number;
  force?: boolean;
}

function writeFile(
  cwd: string,
  relativePath: string,
  content: string,
  options: { force: boolean; executable?: boolean },
  result: ScaffoldResult,
): void {
  const absolute = join(cwd, relativePath);
  if (existsSync(absolute) && !options.force) {
    const current = readFileSync(absolute, "utf8");
    // Our own generated files may be refreshed; user files are never clobbered.
    if (!current.includes(GENERATED_MARKER)) {
      result.skipped.push(relativePath);
      return;
    }
  }

  mkdirSync(dirname(absolute), { recursive: true });
  writeFileSync(absolute, content, "utf8");
  if (options.executable) chmodSync(absolute, 0o755);
  result.written.push(relativePath);
}

export function writeScaffold(cwd: string, options: ScaffoldOptions): ScaffoldResult {
  const result: ScaffoldResult = { written: [], skipped: [] };
  const force = options.force === true;

  writeFile(cwd, ".cnb.yml", buildCnbYml(options), { force }, result);
  writeFile(cwd, ".cnb/agent/run.sh", readTemplate("agent/run.sh").replace(GENERATED_MARKER, GENERATED_MARKER), {
    force,
    executable: true,
  }, result);
  writeFile(
    cwd,
    ".cnb/agent/Dockerfile",
    readTemplate("agent/Dockerfile").replace(GENERATED_MARKER, GENERATED_MARKER),
    { force },
    result,
  );

  const config = {
    apiEndpoint: "https://api.cnb.cool",
    event: options.event,
    testCommand: options.testCommand ?? "npm test",
    maxIterations: options.maxIterations ?? 2,
    pollIntervalMs: 20000,
    autoWatch: true,
    // 云端模型：密钥只放在 CNB 密钥仓库，通过 imports 注入 AGENT_API_KEY。
    model: "<your-model-id>",
    baseUrl: "<https://your-openai-compatible-endpoint/v1>",
    api: "openai-completions",
  };
  writeFile(
    cwd,
    join(".pi", CONFIG_FILE_NAME),
    `${JSON.stringify(config, null, 2)}\n`,
    { force },
    result,
  );

  return result;
}